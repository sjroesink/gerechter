import { admin, expectMobileLayout, login } from './helpers'
import { expect, test } from './test'

test.describe.configure({ mode: 'serial' })

test('catalogus: aanmaken, alias zoeken, wijzigen, omrekening en archiveren op mobiel', async ({ page }) => {
  await login(page, admin.email)
  await page.goto('/meer')
  await page.getByRole('link', { name: /Ingrediënten/ }).click()
  await expectMobileLayout(page)
  await page.getByRole('link', { name: 'Ingrediënt toevoegen' }).click()
  await expectMobileLayout(page)
  await page.getByLabel('Naam', { exact: true }).fill('Tomatenblokjes')
  await page.getByLabel('Andere namen').fill('tomaat in blik')
  await page.getByLabel('Beschikbaar voor').selectOption('global')
  await page.getByRole('button', { name: 'Opslaan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tomatenblokjes', exact: true })).toBeVisible()
  await expect(page.getByText('Globale catalogus', { exact: true })).toBeVisible()
  await expectMobileLayout(page)

  await page.getByLabel('Eenheid omrekenen').selectOption('blik')
  await page.getByLabel('Hoeveelheid in gram').fill('400')
  await page.getByRole('button', { name: 'Omrekening opslaan' }).click()
  await expect(page.getByText('1 blik = 400 g', { exact: true })).toBeVisible()
  await expectMobileLayout(page)
  await page.getByRole('button', { name: 'Gegevens wijzigen' }).click()
  await page.getByLabel('Naam', { exact: true }).fill('Tomaten in blokjes')
  await expect(page.getByLabel('Basiseenheid')).toBeDisabled()
  await page.getByRole('button', { name: 'Opslaan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tomaten in blokjes', exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Terug naar ingrediënten' }).click()
  await page.getByLabel('Zoek ingrediënten').fill('tomaat in blik')
  await page.getByLabel('Zoek ingrediënten').press('Enter')
  await page.getByRole('link', { name: /Tomaten in blokjes/ }).click()
  await page.getByRole('button', { name: 'Archiveren', exact: true }).click()
  await expect(page.getByText('Dit ingrediënt is gearchiveerd.', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: 'Terug naar ingrediënten' }).click()
  await page.getByLabel('Zoek ingrediënten').fill('tomaat in blik')
  await page.getByLabel('Zoek ingrediënten').press('Enter')
  await expect(page.getByRole('link', { name: /Tomaten in blokjes/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Met archief', exact: true }).click()
  await page.getByRole('link', { name: /Tomaten in blokjes/ }).click()
  await page.getByRole('button', { name: 'Herstellen', exact: true }).click()
  await expect(page.getByText('Dit ingrediënt is gearchiveerd.', { exact: false })).toHaveCount(0)
})

test('een gewoon lid kan eigen ingrediënten maken en globale gegevens alleen lezen', async ({ page }) => {
  await login(page, 'sanne@e2e.test')
  await page.goto('/meer/ingredienten')
  await page.getByRole('link', { name: /Tomaten in blokjes/ }).click()
  await expect(page.getByRole('button', { name: 'Gegevens wijzigen' })).toHaveCount(0)
  await expect(page.getByText('1 blik = 400 g', { exact: true })).toBeVisible()
  await page.goto('/meer/ingredienten/nieuw')
  await expect(page.getByLabel('Beschikbaar voor')).toHaveCount(0)
  await page.getByLabel('Naam', { exact: true }).fill('Mijn geheime kruiden')
  await page.getByRole('button', { name: 'Opslaan', exact: true }).click()
  await expect(page.getByText('Eigen ingrediënt van je huishouden', { exact: true })).toBeVisible()
  await expectMobileLayout(page)
})
