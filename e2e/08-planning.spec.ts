import { admin, expectMobileLayout, login } from './helpers'
import { expect, test } from './test'

test.describe.configure({ mode: 'serial' })
test.use({ actionTimeout: 10_000 })
let mealPath = ''

test('weekplanning: gerecht en vrije tekst plannen, verplaatsen, porties en verwijderen', async ({
  page,
}, testInfo) => {
  await login(page, admin.email)
  await page.goto('/week?week=2027-01-01')
  await expect(page.getByText('28 december 2026 – 3 januari 2027', { exact: true })).toBeVisible()
  await expectMobileLayout(page)
  // Een lege dag gaat direct naar "Wat eten we?" voor die datum.
  await page.getByRole('link', { name: /^vrijdag 1 januari/ }).click()
  await expect(page.getByLabel('Datum', { exact: true })).toHaveValue('2027-01-01')
  await expectMobileLayout(page)
  await page.getByLabel('Gerecht zoeken').fill('Tomatensoep')
  await page.getByRole('button', { name: /^Tomatensoep uit eigen keuken/ }).click()
  // Vanuit de keuze naar het recept en terug: de keuze blijft staan.
  await page.getByRole('link', { name: 'Bekijk recept', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tomatensoep uit eigen keuken', level: 1 })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('region', { name: 'Gekozen maaltijd' })).toContainText(
    'Tomatensoep uit eigen keuken',
  )
  await expect(page.getByLabel('Datum', { exact: true })).toHaveValue('2027-01-01')
  await page.getByRole('button', { name: 'Meer personen', exact: true }).click()
  await expect(page.getByText('Vast aantal voor deze maaltijd', { exact: true })).toBeVisible()
  await page.getByLabel('Notitie bij maaltijd').fill('Met z’n drieën eten')
  await expectMobileLayout(page)
  await page.getByRole('button', { name: 'Maaltijd opslaan', exact: true }).click()
  // Na toevoegen terug naar de weekplanning van die datum.
  await expect(page).toHaveURL(/\/week\?week=2027-01-01$/)
  await page.getByRole('link', { name: /Tomatensoep uit eigen keuken/ }).click()
  await expect(page.getByRole('heading', { name: 'Tomatensoep uit eigen keuken', level: 2 })).toBeVisible()
  mealPath = new URL(page.url()).pathname
  await expect(page.getByRole('region', { name: 'Ingrediënten geplande maaltijd' })).toContainText('1,5 blik')
  await expectMobileLayout(page)
  await page.getByRole('link', { name: 'Bekijk recept' }).click()
  await expect(page.getByRole('group', { name: 'Personen' }).getByRole('status')).toHaveText('3')
  await page.goto(mealPath)
  await page.getByRole('link', { name: 'Wijzigen', exact: true }).click()
  await page.getByLabel('Datum', { exact: true }).fill('2027-01-04')
  await page.getByRole('button', { name: 'Huishoudstandaard gebruiken', exact: true }).click()
  await page.getByLabel('Notitie bij maaltijd').fill('Verplaatst naar maandag')
  await page.getByRole('button', { name: 'Maaltijd opslaan', exact: true }).click()
  await expect(page.getByText(/^Huishoudstandaard · recept is voor/)).toBeVisible()
  await expect(page.getByRole('region', { name: 'Ingrediënten geplande maaltijd' })).toContainText('1 blik')
  await page.getByRole('link', { name: 'Terug naar dagplanning' }).click()
  await expect(page).toHaveURL(/\/week\/dag\/2027-01-04$/)
  await page.getByRole('link', { name: 'Maaltijd toevoegen', exact: true }).click()
  await page.getByRole('button', { name: 'Restjes', exact: true }).click()
  await expect(page.getByLabel('Vrije maaltijd', { exact: true })).toHaveValue('Restjes')
  await page.getByLabel('Notitie bij maaltijd').fill('Uit de koelkast')
  await expectMobileLayout(page)
  await page.getByRole('button', { name: 'Maaltijd opslaan', exact: true }).click()
  await expect(page).toHaveURL(/\/week\?week=2027-01-04$/)
  await page.getByRole('link', { name: /Restjes/ }).click()
  await expect(page).toHaveURL(/\/week\/dag\/2027-01-04$/)
  await page.getByRole('link', { name: /Restjes/ }).click()
  await expect(page.getByRole('heading', { name: 'Restjes', level: 2 })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Ingrediënten geplande maaltijd' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Terug naar dagplanning' }).click()
  await expect(page.getByRole('link', { name: /Tomatensoep uit eigen keuken/ })).toBeVisible()
  await expect(page.getByRole('link', { name: /Restjes/ })).toBeVisible()
  await page.getByRole('link', { name: 'Terug naar week' }).click()
  await expect(page.getByText(/^4 – 10 januari( 2027)?$/)).toBeVisible()
  await expectMobileLayout(page)
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.screenshot({ path: testInfo.outputPath('week-dark.png'), fullPage: true })
  // Een dag met meerdere maaltijden opent de dagplanning.
  await page.getByRole('link', { name: /Restjes/ }).click()
  await expect(page).toHaveURL(/\/week\/dag\/2027-01-04$/)
  await page.getByRole('link', { name: /Restjes/ }).click()
  await page.getByRole('button', { name: 'Uit planning verwijderen' }).click()
  await expect(page).toHaveURL(/\/week\/dag\/2027-01-04$/)
  await expect(page.getByRole('link', { name: /Restjes/ })).toHaveCount(0)
  await page.getByRole('link', { name: 'Terug naar week' }).click()
  await page.getByRole('link', { name: 'Vorige week', exact: true }).click()
  await expect(page.getByRole('link', { name: /Tomatensoep uit eigen keuken/ })).toHaveCount(0)
  await page.getByRole('link', { name: 'Volgende week', exact: true }).click()
  await expect(page.getByRole('link', { name: /Tomatensoep uit eigen keuken/ })).toBeVisible()
})

test('planning en directe item-IDs blijven afgeschermd voor een ander huishouden', async ({ page }) => {
  await login(page, 'sanne@e2e.test')
  await page.goto('/week?week=2027-01-04')
  await expect(page.getByRole('link', { name: /Tomatensoep uit eigen keuken/ })).toHaveCount(0)
  await page.goto(mealPath)
  await expect(page.getByRole('alert')).toHaveText('Geplande maaltijd niet gevonden.')
})
