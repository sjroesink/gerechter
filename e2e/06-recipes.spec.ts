import { admin, expectMobileLayout, login } from './helpers'
import { expect, test } from './test'

test.describe.configure({ mode: 'serial' })
test.use({ actionTimeout: 10_000 })
let recipePath = ''

test('gerecht met porties, vaste secties, timer en checklist aanmaken, wijzigen en herstellen', async ({
  page,
}, testInfo) => {
  await login(page, admin.email)
  await page.goto('/gerechten')
  await page.getByRole('link', { name: 'Nieuw gerecht' }).click()
  await page.getByLabel('Naam van het gerecht').fill('Tomatensoep')
  await page.getByLabel('Beschrijving', { exact: true }).fill('Een eenvoudige soep met tomaten uit blik.')
  await page.getByLabel('Porties', { exact: true }).fill('2')
  await page.getByLabel('Tags', { exact: true }).fill('snel, vegetarisch')
  await page.getByLabel('Ingrediënt zoeken').fill('tomaat in blik')
  await page.getByRole('button', { name: 'Zoek ingrediënt', exact: true }).click()
  await page.getByRole('button', { name: 'Tomaten in blokjes', exact: true }).click()
  await page.getByLabel('Hoeveelheid', { exact: true }).fill('1')
  await page.getByRole('combobox', { name: 'Eenheid', exact: true }).selectOption('blik')
  await page.getByLabel('Tekst Bereiding').fill('Verwarm de tomaten en pureer de soep.')
  const cooking = page.getByRole('group', { name: 'Bereiding', exact: true })
  await cooking.getByRole('button', { name: 'Kookwekker toevoegen' }).click()
  await cooking.getByLabel('Naam kookwekker').fill('Soep')
  await cooking.getByLabel('Tijd (minuten)').fill('1')
  await cooking.getByRole('button', { name: 'Checklist toevoegen' }).click()
  await cooking.getByLabel('Checklist (één taak per regel)').fill('Roeren\nProeven')
  await cooking.getByRole('button', { name: 'Tip toevoegen' }).click()
  await cooking.getByLabel('Tip', { exact: true }).fill('Let op: <b>heet</b>.')
  await expectMobileLayout(page)
  await page.getByRole('button', { name: 'Gerecht opslaan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tomatensoep', exact: true })).toBeVisible()
  recipePath = new URL(page.url()).pathname
  await expect(page.getByText('Verwarm de tomaten en pureer de soep.', { exact: true })).toBeVisible()
  await expect(page.getByText('Let op: <b>heet</b>.', { exact: true })).toBeVisible()
  const persons = page.getByRole('group', { name: 'Personen' })
  await expect(persons.getByRole('status')).toHaveText('2')
  await persons.getByRole('button', { name: 'Meer personen' }).click()
  await persons.getByRole('button', { name: 'Meer personen' }).click()
  await expect(persons.getByRole('status')).toHaveText('4')
  const tomatoes = page
    .getByRole('region', { name: 'Ingrediëntenlijst' })
    .getByRole('listitem')
    .filter({ hasText: 'Tomaten in blokjes' })
  await expect(tomatoes).toContainText('2 blik')
  await expect(page).toHaveURL(/servings=4/)

  const timer = page.getByRole('region', { name: 'Kookwekker Soep' })
  await expect(timer.getByRole('timer')).toHaveText('1:00')
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  await timer.getByRole('button', { name: 'Starten', exact: true }).click()
  await page.clock.runFor(10_000)
  await expect(timer.getByRole('timer')).toHaveText('0:50')
  await timer.getByRole('button', { name: 'Pauzeren', exact: true }).click()
  await page.clock.runFor(5000)
  await expect(timer.getByRole('timer')).toHaveText('0:50')
  await timer.getByRole('button', { name: 'Herstellen', exact: true }).click()
  await expect(timer.getByRole('timer')).toHaveText('1:00')
  await page.getByRole('checkbox', { name: 'Roeren', exact: true }).check()
  await expect(page.getByRole('checkbox', { name: 'Roeren', exact: true })).toBeChecked()
  await page.clock.resume()
  await expectMobileLayout(page)
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: testInfo.outputPath('recipe-dark.png'), fullPage: true })

  await page.getByRole('link', { name: 'Gerecht bewerken' }).click()
  await expect(page.getByLabel('Porties', { exact: true })).toHaveValue('2')
  await page.getByLabel('Naam van het gerecht').fill('Tomatensoep uit eigen keuken')
  await page.getByRole('button', { name: 'Gerecht opslaan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tomatensoep uit eigen keuken', exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Roeren', exact: true })).not.toBeChecked()
  await expect(tomatoes).toContainText('1 blik')
  await page.getByRole('button', { name: 'Gerecht archiveren' }).click()
  await expect(page.getByText('Dit gerecht is gearchiveerd.', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: 'Terug naar gerechten' }).click()
  await page.getByLabel('Zoek gerechten').fill('snel')
  await page.getByLabel('Zoek gerechten').press('Enter')
  await expect(page).toHaveURL(/query=snel/)
  await page.getByRole('link', { name: 'Archief tonen' }).click()
  await expect(page.getByRole('link', { name: /Archief verbergen/ })).toBeVisible()
  await page.getByRole('link', { name: /Tomatensoep uit eigen keuken/ }).click()
  await page.getByRole('button', { name: 'Gerecht herstellen' }).click()
  await expect(page.getByText('Dit gerecht is gearchiveerd.', { exact: false })).toHaveCount(0)
})

test('een ander huishouden ziet het gerecht niet en kan een aangepast ID niet gebruiken', async ({
  page,
}) => {
  await login(page, 'sanne@e2e.test')
  await page.goto('/gerechten')
  await expect(page.getByRole('link', { name: /Tomatensoep uit eigen keuken/ })).toHaveCount(0)
  await page.goto(recipePath)
  await expect(page.getByRole('alert')).toHaveText('Gerecht niet gevonden.')
})
